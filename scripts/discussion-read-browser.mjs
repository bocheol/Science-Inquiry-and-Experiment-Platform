import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import pg from "pg";
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || "playwright");
const root = new URL("../output/test-infra/", import.meta.url);
assert.equal(await readFile(new URL("local-postgres-marker.txt", root), "utf8"), "science-inquiry-disposable-postgres16");
const { database, base } = JSON.parse(await readFile(new URL("local-browser-target.json", root), "utf8"));
assert.equal(base, "http://127.0.0.1:3108"); assert.match(database, /^codex_validation_browser_[0-9]+_[a-f0-9]+$/);
const db = new pg.Pool({ host: "127.0.0.1", port: 55416, user: "codex_local", password: (await readFile(new URL("local-postgres-password.txt", root), "utf8")).trim(), database, ssl: false });
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 768, height: 1024 } });
  assert.equal((await context.request.post(`${base}/api/auth/login`, { data: { loginId: "10901", password: "student1234" } })).status(), 200);
  await context.addCookies((await context.cookies()).map(cookie => ({ ...cookie, secure: false })));
  const { data } = await (await context.request.get(`${base}/api/inquiry`)).json();
  assert.equal(data.team.id, "demo_team_1");
  const session = data.session.id, cycle = data.session.cycle.id, date = new Date(Date.now() + 9 * 3600000).toISOString().slice(0, 10);
  const members = (await db.query("SELECT id,user_id FROM team_members WHERE team_id='demo_team_1' AND status='active'")).rows;
  const reader = members.find(row => row.user_id === "demo_student_1"), peer = members.find(row => row.user_id === "demo_student_2");
  assert.ok(reader && peer);
  for (let index = 0; index < 12; index++) {
    const id = `browser_read_${String(index).padStart(2, "0")}`;
    await db.query("INSERT INTO discussion_entries(id,session_id,cycle_id,author_id,kind,activity_date,content) VALUES($1,$2,$3,'demo_student_2','peer',$4,$5)", [id, session, cycle, date, `합성 메시지 ${index}\n` + "스크롤 아래 원문은 아직 읽음 처리하지 않습니다.\n".repeat(18)]);
    await db.query("INSERT INTO discussion_message_recipients(entry_id,membership_id,user_id) VALUES($1,$2,'demo_student_1')", [id, reader.id]);
  }
  await db.query("INSERT INTO discussion_entries(id,session_id,cycle_id,author_id,kind,activity_date,content) VALUES('browser_read_own',$1,$2,'demo_student_1','peer',$3,'보낸 사람 읽음 표시 확인')", [session, cycle, date]);
  await db.query("INSERT INTO discussion_message_recipients(entry_id,membership_id,user_id,read_at) VALUES('browser_read_own',$1,'demo_student_2',CURRENT_TIMESTAMP)", [peer.id]);
  const page = await context.newPage(), errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (request.url().endsWith("/api/discussions") && request.method() === "POST") requests.push(request.postDataJSON()); });
  const readAt = async id => (await db.query("SELECT read_at FROM discussion_message_recipients WHERE entry_id=$1 AND user_id='demo_student_1'", [id])).rows[0].read_at;
  const until = async predicate => { for (let index = 0; index < 100; index++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 100)); } throw new Error("Browser condition timed out"); };
  await page.goto(`${base}/inquiry`);
  await page.getByRole("button", { name: /대화.*기록|활동 기록/ }).first().waitFor();
  assert.equal(requests.filter(item => item.action === "read").length, 0);
  await page.getByRole("button", { name: /대화.*기록|활동 기록/ }).first().click();
  await page.locator('[data-message-id="browser_read_00"]').scrollIntoViewIfNeeded();
  await until(async () => Boolean(await readAt("browser_read_00")));
  assert.equal(await readAt("browser_read_11"), null);
  await page.getByRole("button", { name: "대면 기록", exact: true }).click();
  const before = requests.filter(item => item.action === "read").length;
  await page.waitForTimeout(500);
  assert.equal(requests.filter(item => item.action === "read").length, before);
  assert.equal(await readAt("browser_read_11"), null);
  await page.getByRole("button", { name: "우리끼리 대화", exact: true }).click();
  await page.locator('[data-message-id="browser_read_11"]').scrollIntoViewIfNeeded();
  await until(async () => Boolean(await readAt("browser_read_11")));
  const own = page.locator('[data-message-id="browser_read_own"]');
  await own.getByText("읽음 1/1명", { exact: true }).click();
  const peerName = (await db.query("SELECT name FROM users WHERE id='demo_student_2'")).rows[0].name;
  assert.ok(await own.getByText(peerName, { exact: true }).isVisible());
  assert.equal(await page.locator('[data-message-id="browser_read_11"] summary').count(), 0);
  await page.screenshot({ path: fileURLToPath(new URL("discussion-read-browser-57.png", root)), fullPage: false });
  assert.deepEqual(errors, []);
  await writeFile(new URL("discussion-read-browser-57.json", root), JSON.stringify({ viewport: "768x1024", inactivePanelNoReads: true, belowViewportUnread: true, visibleMessageRead: true, otherTabNoReads: true, authorReceiptsShown: true, otherAuthorReceiptsHidden: true, pageErrors: errors }, null, 2));
  console.log("Browser read receipts: 6 checks passed");
} finally { await browser.close(); await db.end(); }
